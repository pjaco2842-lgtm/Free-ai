#!/usr/bin/env python3
"""What the 25K's rules make possible, computed exactly. No market data needed.

The desk's question is not "which signal?" but "what does this account permit?".
Three rules bound the answer:

  * loss   - $1,000 end-of-day trailing; the floor starts at $24,000
  * target - +$1,250 to pass
  * cons.  - largest single day <= 40% of profit at the moment of passing ($500
             on a clean pass), so a pass always needs at least 3 sessions

Given a stop of k x ATR in dollars and a target of m x risk, every number below
follows from arithmetic plus one assumption: the win rate. It is not a backtest.

    python3 feasibility.py            # writes desk/feasibility.md
"""
from __future__ import annotations

import random
import statistics
from pathlib import Path

ROOT = Path(__file__).resolve().parent
OUT = ROOT / "desk" / "feasibility.md"

START, TARGET, MAX_LOSS, LOCK_AT, LOCK_TRIG, CONS = 25_000, 1_250, 1_000, 25_100, 26_100, 0.40
COST = 2 * 1.24 + 2 * 0.25 * 5.0        # ES micro: commission + one tick each side


def breakeven(risk: float, m: float) -> float:
    """Win rate at which a m x risk target with a 1x risk stop breaks even."""
    return (risk + COST) / (risk * (1 + m))


def ev(risk: float, m: float, p: float) -> float:
    return p * (m * risk) - (1 - p) * risk - COST


def sim(risk, m, p, legs, sessions, trials=20_000, seed=7, freq=1.0):
    """Monte Carlo of the evaluation: one signal per session, sized in contracts.

    `legs` contracts are the SAME trade, so a single outcome is drawn and simply
    multiplied. Drawing an independent outcome per contract would invent
    diversification that does not exist and would make oversized books look safe:
    ten micros stop together, they do not average out.

    Consistency is checked at the moment the target is reached; if it fails the
    account keeps trading, which is what the rule actually requires.
    """
    rng = random.Random(seed)
    out = {"pass": 0, "breach": 0, "unfinished": 0}
    when = []
    for _ in range(trials):
        bal = peak = START
        largest = 0.0
        res = "unfinished"
        n = 0
        for s in range(sessions):
            n = s + 1
            day = 0.0
            if rng.random() < freq:        # a rule that does not trade every session
                win = rng.random() < p
                day = legs * ((m * risk - COST) if win else (-risk - COST))
            bal += day
            largest = max(largest, day)
            peak = max(peak, bal)
            floor = max(peak - MAX_LOSS, LOCK_AT) if peak >= LOCK_TRIG else peak - MAX_LOSS
            if bal < floor:
                res = "breach"
                break
            profit = bal - START
            if profit >= TARGET and largest <= CONS * profit:
                res = "pass"
                break
        out[res] += 1
        if res == "pass":
            when.append(n)
    return {
        "pass": 100.0 * out["pass"] / trials,
        "breach": 100.0 * out["breach"] / trials,
        "median": statistics.median(when) if when else None,
        "p3": 100.0 * sum(1 for w in when if w <= 3) / trials,
        "p5": 100.0 * sum(1 for w in when if w <= 5) / trials,
        "p10": 100.0 * sum(1 for w in when if w <= 10) / trials,
    }


def main() -> None:
    ATR_PTS = 70.0                       # a middling ES ATR(14); the desk's median risk priced ~$413
    MULT = 5.0
    risk1 = ATR_PTS * MULT
    L = ["# What the 25K rules make possible", "",
         "Arithmetic, not a backtest — generated by `trading/feasibility.py`. "
         f"One MES micro, ES ATR(14) = {ATR_PTS:.0f} pts, risk = ${risk1:.0f} at 1.0 ATR, "
         f"round-trip cost ${COST:.2f}.", "",
         "## The win rate each target needs", "",
         "| target | win needed | $/win | $/loss | $/trade @60% | @70% | @78% | @85% |",
         "|---|---:|---:|---:|---:|---:|---:|---:|"]
    for m in (0.2, 0.3, 0.5, 1.0, 1.5, 2.0):
        r = risk1
        L.append(f"| {m}R | {100*breakeven(r, m):.1f}% | ${m*r:.0f} | ${r:.0f} | "
                 f"${ev(r,m,.60):+.0f} | ${ev(r,m,.70):+.0f} | ${ev(r,m,.78):+.0f} | ${ev(r,m,.85):+.0f} |")
    L += ["",
          "Read the last four columns against the second. A 0.2R target wins 85% of the "
          "time and still loses money at an 85% win rate: one loss costs five wins. The "
          "high-win-rate books the desk keeps asking for are the ones with no expectancy. "
          f"0.5R needs **{100*breakeven(risk1, 0.5):.1f}%**, which is the number the whole "
          "live book rests on."]

    L += ["",
          "## Size required to make the three-day number", "",
          "| $/session wanted | micros at 0.5R, 1 trade/leg | risk if every leg stops | share of the $1,000 buffer |",
          "|---:|---:|---:|---:|"]
    for want in (200, 300, 417, 500):
        e = ev(risk1, 0.5, 0.78)
        legs = max(1, round(want / max(e, 1e-9)))
        L.append(f"| ${want} | {legs} | ${legs*risk1:.0f} | {100*legs*risk1/MAX_LOSS:.0f}% |")
    pace = max(1, round(417 / ev(risk1, 0.5, 0.78)))
    L += ["",
          "$417 a session is the three-day pace. At 0.5R and the desk's own 78% win rate "
          f"that is ${ev(risk1,0.5,0.78):.0f}/trade, so it needs ~{pace} micros. {pace} legs "
          f"stopping is ${pace*risk1:.0f} against a ${MAX_LOSS} buffer: one ordinary bad "
          "session ends the evaluation, and there is one account.", "",
          "## The same maths as a walk", "",
          "20,000 simulated evaluations per line. One signal per session, sized in "
          "contracts (all contracts share the outcome), stop-first, costs included, "
          "consistency enforced at the moment the target is reached.", "",
          "| win | target | legs | pass% | within 3 | within 5 | within 10 | breach% | median sessions |",
          "|---|---|---:|---:|---:|---:|---:|---:|---:|"]
    for p in (0.60, 0.70, 0.78, 0.85):
        for m, legs in ((0.5, 1), (0.5, 2), (0.5, 6)):
            s = sim(risk1, m, p, legs, 60)
            med = f"{s['median']:.0f}" if s["median"] is not None else "-"
            L.append(f"| {100*p:.0f}% | {m}R | {legs} | {s['pass']:.0f}% | {s['p3']:.1f}% | "
                     f"{s['p5']:.1f}% | {s['p10']:.1f}% | {s['breach']:.0f}% | {med} |")
    win_usd = 0.5 * risk1
    need = -(-TARGET // win_usd)
    L += ["",
          f"The 0.5R column shows the mechanical truth: {need:.0f} winning trades of "
          f"${win_usd:.0f} are needed to reach ${TARGET:.0f}, so three sessions can only "
          f"work with {need/3:.1f} winners a day and no losses — and the 40% rule caps a "
          f"day at ${CONS*TARGET:.0f}, which is {CONS*TARGET/win_usd:.1f} wins. Adding legs "
          "buys the pace and spends the buffer in the same trade.", ""]

    L += ["## What each ATR stop costs on one MES micro", "",
          "| stop | risk | share of buffer | stop is legal on 25K |", "|---|---:|---:|---|"]
    for k in (0.5, 0.75, 1.0, 1.5, 2.0, 2.5):
        r = k * risk1
        ok = "yes" if r <= MAX_LOSS * 0.5 else ("one trade, no margin for error" if r < MAX_LOSS else "no — a single stop breaches")
        L.append(f"| {k:.2f} ATR | ${r:.0f} | {100*r/MAX_LOSS:.0f}% | {ok} |")
    L += ["",
          "This is why 2.0 and 2.5 ATR are not available on a 25K however good they look: "
          f"${2*risk1:.0f} and ${2.5*risk1:.0f} are 80-100% of the whole risk budget in one "
          "trade. On a 50K ($2,000 buffer) the same stops are 40-50%, which is the real "
          "argument for the 50K, not a better signal.", ""]

    OUT.write_text("\n".join(L) + "\n")
    print("\n".join(L))


if __name__ == "__main__":
    main()
