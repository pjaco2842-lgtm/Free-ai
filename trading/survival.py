#!/usr/bin/env python3
"""Survival-first sizing: the largest size that keeps a pass chance you accept.

The earlier work sized everything at one micro because a stop had to fit inside a
$1,000 buffer. That is right for a single attempt; it is the wrong constraint if you
will re-buy evaluations and only need most attempts to survive.

This answers that question directly: "if I need a 75% or better chance of getting
through, how big can I be, and what does that earn?"

Two things make the answer different from the first version of this script, and both
were bugs found on 2026-10-31:

  * contracts on one signal share one outcome. Drawing a separate win/loss per
    contract invented diversification and made oversized books look safe.
  * a rule that fires once every five sessions is not a rule that trades every
    session. `freq` now models that, so the session counts are real sessions.

The win rate is still an assumption, not a measurement — the one input this script
cannot supply.

    python3 survival.py            # writes desk/survival.md
"""
from __future__ import annotations

from pathlib import Path

import feasibility as F

ROOT = Path(__file__).resolve().parent
OUT = ROOT / "desk" / "survival.md"

RISK = 350.0                      # one MES micro at 1.0 ATR, ES ATR(14) = 70 pts
RATES = (0.65, 0.70, 0.75, 0.78, 0.85)
LEGS = (1, 2, 3, 4, 6, 8, 10)
M = 0.5                           # target as a multiple of risk
TRADES_PER_SESSION = 0.21         # the ES dip book's measured cadence
TRIALS, SESSIONS = 4_000, 60
REAL_SESSIONS = round(SESSIONS / TRADES_PER_SESSION)   # same trading horizon, not the same calendar


def ev_session(legs: int, p: float, freq: float) -> float:
    """Dollars a session on average, at this cadence, full round-trip cost per trade."""
    return freq * legs * F.ev(RISK, M, p)


def frontier(freq: float, sessions: int) -> list[dict]:
    rows = []
    for p in RATES:
        for legs in LEGS:
            s = F.sim(RISK, M, p, legs, sessions, trials=TRIALS, freq=freq)
            rows.append({"p": p, "legs": legs, "pass": s["pass"], "breach": s["breach"],
                         "unf": max(0.0, 100.0 - s["pass"] - s["breach"]),
                         "median": s["median"], "risk": legs * RISK,
                         "ev": ev_session(legs, p, freq)})
    return rows


def table(rows: list[dict]) -> list[str]:
    L = ["| win | micros | risk if all stop | pass% | breach% | unfinished% | median sessions | $/session |",
         "|---|---:|---:|---:|---:|---:|---:|---:|"]
    for r in rows:
        med = f"{r['median']:.0f}" if r["median"] is not None else "-"
        L.append(f"| {100*r['p']:.0f}% | {r['legs']} | ${r['risk']:,.0f} | {r['pass']:.0f}% | "
                 f"{r['breach']:.0f}% | {r['unf']:.0f}% | {med} | ${r['ev']:+,.0f} |")
    return L


def pick(rows: list[dict], floor: float, p: float) -> dict | None:
    ok = [r for r in rows if r["p"] == p and r["pass"] >= floor]
    return max(ok, key=lambda r: r["legs"]) if ok else None


def floors(rows: list[dict], label: str) -> list[str]:
    L = []
    for floor in (75, 90):
        L += [f"**Largest size keeping a {floor}% pass chance{label}:**", ""]
        for p in RATES:
            b = pick(rows, floor, p)
            L.append(f"- {100*p:.0f}% win → " + (
                f"{b['legs']} micros, ${b['risk']:,.0f} of risk, {b['pass']:.0f}% pass, "
                f"${b['ev']:+,.0f}/session" if b
                else f"no size reaches {floor}% (best is "
                     f"{max((r['pass'] for r in rows if r['p'] == p), default=0):.0f}%)"))
        L.append("")
    return L


def main() -> None:
    daily = frontier(1.0, SESSIONS)
    real = frontier(TRADES_PER_SESSION, REAL_SESSIONS)

    one = next(r for r in daily if r["p"] == 0.78 and r["legs"] == 1)
    two = next(r for r in daily if r["p"] == 0.78 and r["legs"] == 2)
    rone = next(r for r in real if r["p"] == 0.78 and r["legs"] == 1)
    rtwo = next(r for r in real if r["p"] == 0.78 and r["legs"] == 2)

    L = ["# Survival-first sizing", "",
         "Generated by `trading/survival.py` on the account walk in `feasibility.py`: "
         "$25,000, +$1,250 target, $1,000 end-of-day trailing floor locking at $25,100, "
         "40% consistency, stop-first, costs in. "
         f"{TRIALS:,} walks per line, {SESSIONS} sessions of trading — which is "
         f"{REAL_SESSIONS} calendar sessions at {TRADES_PER_SESSION:.2f} trades a session.",
         "",
         f"One MES micro at 1.0 ATR = **${RISK:,.0f}** of risk; `micros` is how many contracts "
         f"go on the *same* signal, so a stop costs that many times ${RISK:,.0f}. Target "
         f"{M}R. **The win rate is an assumption, not a measurement.**", "",
         "## If the rule traded every session", ""]
    L += table(daily) + [""] + floors(daily, " (daily trading)")

    L += [f"## At the book's real cadence — {TRADES_PER_SESSION:.2f} trades a session", "",
          "Same walk, but four sessions in five are flat. Slower, and with more sessions in "
          "which a losing streak can happen.", ""]
    L += table(real) + [""] + floors(real, " (0.21 trades/session)")

    L += ["## What the correction changed", "",
          "The first version of this script drew an independent win/loss for every contract. "
          "That is not how a position works: ten micros on one signal stop together. The "
          "effect was large and it went the wrong way — it made size look safe.",
          "",
          f"- 78% win, 1 micro: **{one['pass']:.0f}%** pass ({one['breach']:.0f}% breach), "
          f"median {one['median']:.0f} sessions at a daily cadence.",
          f"- 78% win, 2 micros: **{two['pass']:.0f}%** pass ({two['breach']:.0f}% breach), "
          f"median {two['median']:.0f} sessions. The old model said 82% — that number was an "
          "artefact and is retracted.",
          f"- 78% win, at 0.21 trades/session: 1 micro **{rone['pass']:.0f}%** pass "
          f"({rone['breach']:.0f}% breach), median {rone['median']:.0f} sessions; 2 micros "
          f"**{rtwo['pass']:.0f}%** pass ({rtwo['breach']:.0f}% breach), median "
          f"{rtwo['median']:.0f} sessions.",
          "",
          "So on this rule **size does not buy survival, it spends it.** At a 78% win rate "
          "the 75% floor is met by one micro and not by two, because two micros turn one "
          "ordinary loss into 70% of the buffer and the 40% consistency rule caps how fast "
          "the profit can be booked. The size that satisfies a 75% survival preference is "
          "**one micro** — which is also the size that was already chosen, for different "
          "reasons.", ""]

    L += ["## Many attempts: the arithmetic you are describing", "",
          "Per attempt, a funded evaluation is worth `V` and an evaluation fee costs `C`. "
          "Trying `N` accounts:", "",
          "```", "expected funded  = N x p", "EV per attempt   = p x V - C",
          "break-even p*    = C / V", "```", "",
          "| fee as a share of what a pass is worth | pass chance needed |", "|---|---:|"]
    for share in (0.05, 0.10, 0.15, 0.20, 0.30, 0.50):
        L.append(f"| {100*share:.0f}% | {100*share:.0f}% |")
    L += ["", "If the fee is a fifth of what a pass is worth to you, anything above 20% pass "
          "is positive EV. A 75% floor is therefore a comfort threshold, not an economic one "
          "— the economic one is `p > C/V`, and it is far lower. What many attempts does "
          "**not** fix is an edge that is negative per trade: five copies of a losing rule "
          "is five losing accounts, and the fee is paid every time.", ""]

    L += ["## What this cannot tell you", "",
          "The win rate, the fill resolution and the true cadence. Everything here is "
          "arithmetic conditional on those three, and the sweep that produced the 78% is the "
          "one retracted in `RESEARCH-LOG.md` (o). Use it to choose a size once the causal "
          "re-measurement exists — not as evidence that the rule works.", ""]

    OUT.write_text("\n".join(L) + "\n")
    print("\n".join(L))


if __name__ == "__main__":
    main()
